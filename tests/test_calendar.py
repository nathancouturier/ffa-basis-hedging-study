@pytest.mark.parametrize("year", sorted(PUBLISHED))
def test_bank_holidays_match_the_published_list(year):
    assert sorted(calendar.bank_holidays(year)) == PUBLISHED[year]


def test_2026_month_lengths_match_the_baltic_prints():
    # Every publication day of January to October 2026 is printed on handybulk.com (data/AUDIT.md).
    expected = {
        "2026-01": 21,
        "2026-02": 20,
        "2026-03": 22,
        "2026-04": 20,
        "2026-05": 19,
        "2026-06": 22,
        "2026-07": 23,
        "2026-08": 20,
        "2026-09": 22,
        "2026-10": 22,
    }
    for month, count in expected.items():
        assert len(calendar.publication_days(month)) == count


def test_previous_publication_day_skips_weekends_and_holidays():
    assert calendar.previous_publication_day("2026-04-07") == "2026-04-02"
    assert calendar.previous_publication_day("2026-07-06") == "2026-07-03"
